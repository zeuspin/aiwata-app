export function getPortraitDesign(preset, design) {
  const portrait = botPortraits[preset]
  const defaults = {
    hair: preset, accessory: portrait.accessory ?? 'none', face: portrait.face,
    skin: preset, hairColor: preset, eyeColor: 'ink', clothing: preset, background: 'charcoal',
  }
  return Object.fromEntries(Object.entries(portraitDesignFields).map(([field, { options }]) => {
    const selected = design?.[field]
    return [field, Object.hasOwn(options, selected) ? selected : defaults[field]]
  }))
}

function luminance(color) {
  const channels = color.slice(1).match(/../g).map(hex => {
    const channel = parseInt(hex, 16) / 255
    return channel <= .04045 ? channel / 12.92 : ((channel + .055) / 1.055) ** 2.4
  })
  return .2126 * channels[0] + .7152 * channels[1] + .0722 * channels[2]
}

const hairColorsByBackground = Object.fromEntries(Object.entries(portraitBackgroundColors).map(([key, color]) => {
  const bg = luminance(color)
  return [key, Object.keys(portraitHairColors).filter(id => portraitHairColors[id].every(tone => {
    const hair = luminance(tone)
    return (Math.max(hair, bg) + .05) / (Math.min(hair, bg) + .05) >= 3
  }))]
}))

const pick = values => values[Math.floor(Math.random() * values.length)]

function shuffled(values) {
  const items = [...values]
  for (let index = items.length - 1; index > 0; index--) {
    const other = Math.floor(Math.random() * (index + 1))
    ;[items[index], items[other]] = [items[other], items[index]]
  }
  return items
}

export function randomPortraitBatch() {
  const light = shuffled(['ivory', 'mint', 'lilac', 'sky'])
  const dark = shuffled(['charcoal', 'navy', 'pine', 'wine'])
  return shuffled(Object.keys(botPortraits)).map((hair, index) => {
    const palette = index % 2 === 0 ? light : dark
    const background = palette[Math.floor(index / 2) % palette.length]
    return {
      ...Object.fromEntries(Object.entries(portraitDesignFields).map(([field, { options }]) => [field, pick(Object.keys(options))])),
      hair, background, hairColor: pick(hairColorsByBackground[background]),
    }
  })
}

export function resolveBotPortrait(preset, design) {
  const base = botPortraits[preset]
  if (!design) return base
  const { back, front, sheen } = botPortraits[design.hair]
  return {
    ...base, back, front, sheen, face: design.face, accessory: design.accessory,
    skin: botPortraits[design.skin].skin, hair: portraitHairColors[design.hairColor],
    shirt: botPortraits[design.clothing].shirt, eyeColor: portraitEyeColors[design.eyeColor],
    background: portraitBackgroundColors[design.background],
  }
}
